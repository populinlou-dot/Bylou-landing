-- (a) admin_upsert_class_type -----------------------------------------------------------------------
-- p_id is generated by the client once per form: a retry (double click, network error) with the same
-- id updates the row it created instead of inserting a duplicate. The slug is derived from the name on
-- insert only (unique; suffixed with a hash of the id on collision) and never changes afterwards.
create function public.admin_upsert_class_type(
  p_id                       uuid,
  p_name                     text,
  p_description              text,
  p_default_duration_minutes int,
  p_default_capacity         int,
  p_default_modality         text,
  p_is_published             boolean,
  p_sort_order               int default null)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_name        text := pg_catalog.btrim(p_name);
  v_description text := nullif(pg_catalog.btrim(p_description), '');
  v_slug        text;
  v_sort        int;
  v_created     boolean;
  v_upcoming    int;
begin
  perform private.assert_staff();
  if p_id is null or v_name is null or char_length(v_name) not between 1 and 80
     or char_length(v_description) > 2000
     or p_default_duration_minutes is null or p_default_duration_minutes not between 10 and 480
     or p_default_capacity is null or p_default_capacity not between 1 and 100
     or p_default_modality is null or p_default_modality not in ('in_person', 'online')
     or p_is_published is null
     or (p_sort_order is not null and p_sort_order not between 0 and 10000) then
    raise exception 'invalid_input' using errcode = '22023';
  end if;

  -- Serialize calls sharing an id (double click): the second one becomes an update.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('admin_upsert_class_type:' || p_id::text, 0));

  v_slug := pg_catalog.lower(v_name);
  v_slug := pg_catalog.translate(v_slug, 'áàäâãéèëêíìïîóòöôõúùüûñç', 'aaaaaeeeeiiiiooooouuuunc');
  v_slug := pg_catalog.btrim(pg_catalog.regexp_replace(v_slug, '[^a-z0-9]+', '-', 'g'), '-');
  v_slug := pg_catalog.rtrim(pg_catalog.left(v_slug, 50), '-');
  if char_length(v_slug) < 2 then v_slug := 'class-type'; end if;
  if exists (select 1 from public.class_types ct where ct.slug = v_slug and ct.id <> p_id) then
    v_slug := v_slug || '-' || pg_catalog.left(pg_catalog.md5(p_id::text), 8);
  end if;

  select coalesce(p_sort_order, ct.sort_order) into v_sort from public.class_types ct where ct.id = p_id;
  if not found then
    v_sort := coalesce(p_sort_order, (select coalesce(max(ct.sort_order), 0) + 1 from public.class_types ct));
  end if;

  insert into public.class_types as ct (id, slug, name, description, default_duration_minutes, default_capacity,
                                        default_modality, is_published, sort_order)
  values (p_id, v_slug, v_name, v_description, p_default_duration_minutes, p_default_capacity,
          p_default_modality, p_is_published, v_sort)
  on conflict (id) do update
     set name = excluded.name, description = excluded.description,
         default_duration_minutes = excluded.default_duration_minutes,
         default_capacity = excluded.default_capacity, default_modality = excluded.default_modality,
         is_published = excluded.is_published, sort_order = excluded.sort_order
  returning (ct.xmax = 0) into v_created;

  -- Scheduled sessions still ahead: the UI warns that archiving hides them from the agenda.
  select count(*)::int into v_upcoming from public.sessions s
   where s.class_type_id = p_id and s.status = 'scheduled' and s.starts_at > now();

  return jsonb_build_object('ok', true, 'code', null, 'class_type_id', p_id, 'created', v_created,
    'is_published', p_is_published, 'upcoming_sessions', v_upcoming);
end $$;

-- (b) admin_update_session --------------------------------------------------------------------------
-- LOCK 1 only (session row), the same first lock book_session / cancel_booking take, so a booking and
-- a capacity decrease are serialized: confirmed_count can never exceed capacity (CHECK backstop).
-- "Started" covers in-progress and finished sessions: booking is closed from starts_at on.
-- Setting the current value again is a no-op (changed: false), so retries are safe.
create function public.admin_update_session(p_session_id uuid, p_capacity int)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_session public.sessions%rowtype;
begin
  perform private.assert_staff();
  if p_session_id is null or p_capacity is null or p_capacity not between 1 and 100 then
    raise exception 'invalid_input' using errcode = '22023';
  end if;

  select * into v_session from public.sessions where id = p_session_id for update;            -- LOCK 1
  if not found then return private.fail('not_found'); end if;
  if v_session.status = 'cancelled' then return private.fail('session_cancelled'); end if;
  if now() >= v_session.starts_at then return private.fail('session_started'); end if;
  if p_capacity < v_session.confirmed_count then
    return private.fail('capacity_below_bookings', jsonb_build_object('confirmed_count', v_session.confirmed_count));
  end if;

  if p_capacity <> v_session.capacity then
    update public.sessions set capacity = p_capacity where id = v_session.id;
    -- Phase 4.4: a capacity increase calls private.promote_waitlist_locked(v_session.id) here.
  end if;

  return jsonb_build_object('ok', true, 'code', null, 'session_id', v_session.id, 'capacity', p_capacity,
    'confirmed_count', v_session.confirmed_count, 'changed', p_capacity <> v_session.capacity);
end $$;

-- (c) admin_cancel_session --------------------------------------------------------------------------
-- Identical to migration 7 except the typed '{}'::uuid[] initializer (lint fix).
create or replace function public.admin_cancel_session(p_session_id uuid, p_reason text default null)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_staff     uuid := (select auth.uid());
  v_session   public.sessions%rowtype;
  v_booking   public.bookings%rowtype;
  v_note      text := left('session cancelled' || coalesce(': ' || p_reason, ''), 200);
  v_cancelled int := 0;
  v_refunded  int := 0;
  v_skipped   uuid[] := '{}'::uuid[];
begin
  perform private.assert_staff();
  if p_session_id is null then raise exception 'invalid_input' using errcode = '22023'; end if;

  select * into v_session from public.sessions where id = p_session_id for update;            -- LOCK 1
  if not found then return private.fail('not_found'); end if;
  if v_session.status = 'cancelled' then
    return jsonb_build_object('ok', true, 'code', null, 'session_id', v_session.id, 'replayed', true,
      'cancelled_bookings', 0, 'refunded', 0, 'refunds_skipped', '[]'::jsonb);
  end if;

  perform 1 from public.bookings b                                                             -- LOCK 2
   where b.session_id = v_session.id and b.status = 'confirmed' order by b.id for update;
  perform 1 from public.credit_grants g                                                        -- LOCK 4
   where g.id in (select b.credit_grant_id from public.bookings b
                   where b.session_id = v_session.id and b.status = 'confirmed')
   order by g.id for update;

  for v_booking in
    select * from public.bookings b where b.session_id = v_session.id and b.status = 'confirmed' order by b.id
  loop
    update public.bookings set status = 'cancelled', cancelled_at = now(), cancelled_by = v_staff
     where id = v_booking.id;
    v_cancelled := v_cancelled + 1;

    if v_booking.credit_grant_id is not null then
      update public.credit_grants set credits_remaining = credits_remaining + v_booking.credits_debited
       where id = v_booking.credit_grant_id and expires_at > now();
      if found then
        insert into public.credit_ledger (user_id, grant_id, booking_id, reason, delta, actor_id, note)
        values (v_booking.user_id, v_booking.credit_grant_id, v_booking.id, 'cancel_refund',
                v_booking.credits_debited, v_staff, v_note);
        update public.bookings set refunded = true where id = v_booking.id;
        v_refunded := v_refunded + 1;
      else
        v_skipped := v_skipped || v_booking.id;
      end if;
    end if;
  end loop;

  update public.sessions set status = 'cancelled', cancelled_at = now(), confirmed_count = 0
   where id = v_session.id;

  return jsonb_build_object('ok', true, 'code', null, 'session_id', v_session.id, 'replayed', false,
    'cancelled_bookings', v_cancelled, 'refunded', v_refunded, 'refunds_skipped', to_jsonb(v_skipped));
end $$;

